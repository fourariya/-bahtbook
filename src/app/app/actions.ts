"use server";

import { revalidatePath } from "next/cache";

import type { ActionResult } from "@/lib/finance/types";
import {
  categoryCreateSchema,
  categoryUpdateSchema,
  fieldErrorsOf,
  idSchema,
  transactionInputSchema,
} from "@/lib/finance/validation";
import { createClient, type ServerSupabaseClient } from "@/lib/supabase/server";

/**
 * Every action here:
 *   1. confirms there is a signed-in user (asking the Auth server, not trusting the cookie),
 *   2. validates its input again on the server,
 *   3. writes through the user's own session, so Row Level Security applies.
 * user_id is never taken from the client; the database fills it from auth.uid().
 */

const SESSION_EXPIRED: ActionResult = {
  ok: false,
  message: "เซสชันหมดอายุ กรุณาเข้าสู่ระบบอีกครั้ง",
};
const UNEXPECTED: ActionResult = {
  ok: false,
  message: "บันทึกไม่สำเร็จ กรุณาลองใหม่อีกครั้ง",
};

const UNIQUE_VIOLATION = "23505";
const FOREIGN_KEY_VIOLATION = "23503";

async function authenticate(): Promise<ServerSupabaseClient | null> {
  const supabase = await createClient();
  if (!supabase) return null;
  const { data, error } = await supabase.auth.getUser();
  return error || !data.user ? null : supabase;
}

function logFailure(operation: string, code: string | undefined) {
  // Only the operation name and the Postgres error code are logged, never row data.
  console.error(`[workspace] ${operation} failed`, { code: code ?? "unknown" });
}

function refreshWorkspace() {
  revalidatePath("/app", "layout");
}

export async function saveTransaction(
  values: unknown,
  mode: "create" | "update",
): Promise<ActionResult> {
  const supabase = await authenticate();
  if (!supabase) return SESSION_EXPIRED;

  const parsed = transactionInputSchema.safeParse(values);
  if (!parsed.success) {
    return {
      ok: false,
      message: "ตรวจสอบข้อมูลที่กรอกอีกครั้ง",
      fieldErrors: fieldErrorsOf(parsed.error),
    };
  }
  const input = parsed.data;
  const row = {
    category_id: input.categoryId,
    type: input.type,
    amount_satang: input.amount,
    description: input.description,
    transaction_date: input.date,
  };

  if (mode === "create") {
    // The id is generated by the form, so a repeated submit of the same form
    // hits the primary key instead of creating a second row.
    const { error } = await supabase.from("transactions").insert({ id: input.id, ...row });
    if (error?.code === UNIQUE_VIOLATION) {
      const { data: existing } = await supabase
        .from("transactions")
        .select("id")
        .eq("id", input.id)
        .maybeSingle();
      if (!existing) return UNEXPECTED;
    } else if (error?.code === FOREIGN_KEY_VIOLATION) {
      return {
        ok: false,
        message: "หมวดหมู่ที่เลือกใช้กับรายการประเภทนี้ไม่ได้",
        fieldErrors: { categoryId: "เลือกหมวดหมู่ที่ตรงกับประเภทรายการ" },
      };
    } else if (error) {
      logFailure("create transaction", error.code);
      return UNEXPECTED;
    }
    refreshWorkspace();
    return { ok: true, message: "บันทึกรายการแล้ว" };
  }

  const { data, error } = await supabase
    .from("transactions")
    .update(row)
    .eq("id", input.id)
    .select("id");

  if (error?.code === FOREIGN_KEY_VIOLATION) {
    return {
      ok: false,
      message: "หมวดหมู่ที่เลือกใช้กับรายการประเภทนี้ไม่ได้",
      fieldErrors: { categoryId: "เลือกหมวดหมู่ที่ตรงกับประเภทรายการ" },
    };
  }
  if (error) {
    logFailure("update transaction", error.code);
    return UNEXPECTED;
  }
  if (data.length === 0) {
    refreshWorkspace();
    return { ok: false, message: "ไม่พบรายการนี้ อาจถูกลบไปแล้ว" };
  }
  refreshWorkspace();
  return { ok: true, message: "แก้ไขรายการแล้ว" };
}

export async function deleteTransaction(id: unknown): Promise<ActionResult> {
  const supabase = await authenticate();
  if (!supabase) return SESSION_EXPIRED;

  const parsed = idSchema.safeParse(id);
  if (!parsed.success) return { ok: false, message: "ไม่พบรายการนี้" };

  const { error } = await supabase.from("transactions").delete().eq("id", parsed.data);
  if (error) {
    logFailure("delete transaction", error.code);
    return { ok: false, message: "ลบรายการไม่สำเร็จ กรุณาลองใหม่อีกครั้ง" };
  }
  refreshWorkspace();
  return { ok: true, message: "ลบรายการแล้ว" };
}

export async function createCategory(values: unknown): Promise<ActionResult> {
  const supabase = await authenticate();
  if (!supabase) return SESSION_EXPIRED;

  const parsed = categoryCreateSchema.safeParse(values);
  if (!parsed.success) {
    return {
      ok: false,
      message: "ตรวจสอบข้อมูลที่กรอกอีกครั้ง",
      fieldErrors: fieldErrorsOf(parsed.error),
    };
  }

  const { error } = await supabase.from("categories").insert(parsed.data);
  if (error?.code === UNIQUE_VIOLATION) {
    return {
      ok: false,
      message: "มีหมวดหมู่ชื่อนี้อยู่แล้ว",
      fieldErrors: { name: "มีหมวดหมู่ชื่อนี้ในประเภทเดียวกันอยู่แล้ว" },
    };
  }
  if (error) {
    logFailure("create category", error.code);
    return UNEXPECTED;
  }
  refreshWorkspace();
  return { ok: true, message: "เพิ่มหมวดหมู่แล้ว" };
}

export async function updateCategory(values: unknown): Promise<ActionResult> {
  const supabase = await authenticate();
  if (!supabase) return SESSION_EXPIRED;

  const parsed = categoryUpdateSchema.safeParse(values);
  if (!parsed.success) {
    return {
      ok: false,
      message: "ตรวจสอบข้อมูลที่กรอกอีกครั้ง",
      fieldErrors: fieldErrorsOf(parsed.error),
    };
  }

  const { data, error } = await supabase
    .from("categories")
    .update({ name: parsed.data.name, color: parsed.data.color })
    .eq("id", parsed.data.id)
    .select("id");

  if (error?.code === UNIQUE_VIOLATION) {
    return {
      ok: false,
      message: "มีหมวดหมู่ชื่อนี้อยู่แล้ว",
      fieldErrors: { name: "มีหมวดหมู่ชื่อนี้ในประเภทเดียวกันอยู่แล้ว" },
    };
  }
  if (error) {
    logFailure("update category", error.code);
    return UNEXPECTED;
  }
  refreshWorkspace();
  if (data.length === 0) return { ok: false, message: "ไม่พบหมวดหมู่นี้ อาจถูกลบไปแล้ว" };
  return { ok: true, message: "แก้ไขหมวดหมู่แล้ว" };
}

export async function deleteCategory(id: unknown): Promise<ActionResult> {
  const supabase = await authenticate();
  if (!supabase) return SESSION_EXPIRED;

  const parsed = idSchema.safeParse(id);
  if (!parsed.success) return { ok: false, message: "ไม่พบหมวดหมู่นี้" };

  const { error } = await supabase.from("categories").delete().eq("id", parsed.data);
  if (error?.code === FOREIGN_KEY_VIOLATION) {
    // The database refuses to orphan transactions; report it instead of forcing it.
    return {
      ok: false,
      message: "ลบไม่ได้ เพราะยังมีรายการที่ใช้หมวดหมู่นี้ ย้ายรายการไปหมวดอื่นก่อน",
    };
  }
  if (error) {
    logFailure("delete category", error.code);
    return { ok: false, message: "ลบหมวดหมู่ไม่สำเร็จ กรุณาลองใหม่อีกครั้ง" };
  }
  refreshWorkspace();
  return { ok: true, message: "ลบหมวดหมู่แล้ว" };
}
